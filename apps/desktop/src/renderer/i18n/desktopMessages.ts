export function formatDesktopMessage(
    locale: DesktopUiLocale,
    key: keyof DesktopMessageTable,
    vars?: Record<string, string | number>,
): string {
    const raw = DESKTOP_MESSAGES[locale]?.[key] ?? DESKTOP_MESSAGES["en-US"][key] ?? String(key);
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_match, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
